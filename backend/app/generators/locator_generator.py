
import json
import re
from pathlib import Path
from datetime import datetime, timezone


PROJECT_ROOT = Path(__file__).resolve().parents[3]

INPUT_FILE = (
    PROJECT_ROOT
    / "generated"
    / "test_cases"
    / "reviewed_test_cases.json"
)

OUTPUT_DIR = (
    PROJECT_ROOT
    / "generated"
    / "frameworks"
    / "playwright_project"
)

PAGES_DIR = OUTPUT_DIR / "pages"

LOCATOR_JSON = OUTPUT_DIR / "locator_definitions.json"
LOCATOR_JS = PAGES_DIR / "locators.js"


class LocatorGenerator:

    def __init__(self):
        PAGES_DIR.mkdir(parents=True, exist_ok=True)

    def load_approved_test_cases(self):
        if not INPUT_FILE.exists():
            raise FileNotFoundError(
                f"Reviewed test cases not found: {INPUT_FILE}"
            )

        with open(INPUT_FILE, "r", encoding="utf-8") as file:
            data = json.load(file)

        if isinstance(data, dict):
            cases = data.get("test_cases", [])
        elif isinstance(data, list):
            cases = data
        else:
            raise ValueError("Invalid test-case JSON structure.")

        approved = [
            case for case in cases
            if case.get("review_status") == "approved"
        ]

        print(f"Total test cases: {len(cases)}")
        print(f"Approved test cases: {len(approved)}")

        return approved

    @staticmethod
    def extract_placeholder(test_steps):
        """Find an explicitly documented placeholder."""

        for step in test_steps:
            match = re.search(
                r"placeholder text equals ['\"](.+?)['\"]",
                step,
                re.IGNORECASE
            )

            if match:
                return match.group(1)

        return None

    @staticmethod
    def make_function_name(test_case_id):
        """Create a valid JavaScript function name."""

        clean_id = re.sub(
            r"[^a-zA-Z0-9]+",
            "_",
            test_case_id
        )

        return f"get{clean_id.title().replace('_', '')}TodoInput"

    def generate_locator_definition(self, test_case):

        test_case_id = test_case.get(
            "test_case_id", "UNKNOWN"
        )

        steps = test_case.get("test_steps", [])

        placeholder = self.extract_placeholder(steps)

        if placeholder:
            return {
                "test_case_id": test_case_id,
                "element_name": "todo_input",
                "strategy": "getByPlaceholder",
                "value": placeholder,
                "options": {
                    "exact": True
                },
                "function_name": self.make_function_name(
                    test_case_id
                ),
                "source": "test_steps",
                "confidence": "high"
            }

        raise ValueError(
            f"No supported locator information found for "
            f"{test_case_id}. A selector cannot be safely invented."
        )

    def generate_javascript(self, definitions):

        lines = [
            "// AUTO-GENERATED FILE.",
            "// Do not edit manually.",
            "// Generated by LocatorGenerator.",
            "",
        ]

        for definition in definitions:

            function_name = definition["function_name"]
            placeholder = json.dumps(
                definition["value"],
                ensure_ascii=False
            )

            lines.extend([
                f"/** Locator for {definition['test_case_id']} */",
                f"export function {function_name}(page) {{",
                "    return page.getByPlaceholder(",
                f"        {placeholder},",
                "        { exact: true }",
                "    );",
                "}",
                "",
            ])

        return "\n".join(lines)

    def run(self):

        print("\n======================================")
        print(" LOCATOR GENERATOR")
        print("======================================")

        approved_cases = self.load_approved_test_cases()

        if not approved_cases:
            print("No approved test cases found.")
            return

        definitions = []
        failures = []

        for test_case in approved_cases:

            test_case_id = test_case.get(
                "test_case_id", "UNKNOWN"
            )

            try:
                definition = self.generate_locator_definition(
                    test_case
                )

                definitions.append(definition)

                print(
                    f"Locator generated: {test_case_id} "
                    f"-> {definition['strategy']}"
                )

            except Exception as error:

                failures.append({
                    "test_case_id": test_case_id,
                    "error": str(error)
                })

                print(f"Locator generation failed: {error}")

        # Save locator metadata.
        metadata = {
            "generated_at": datetime.now(
                timezone.utc
            ).isoformat(),
            "total_definitions": len(definitions),
            "definitions": definitions,
            "failures": failures
        }

        LOCATOR_JSON.write_text(
            json.dumps(metadata, indent=4, ensure_ascii=False),
            encoding="utf-8"
        )

        # Save reusable JavaScript functions.
        if definitions:
            javascript = self.generate_javascript(definitions)

            LOCATOR_JS.write_text(
                javascript,
                encoding="utf-8"
            )

        print("\n========== LOCATOR SUMMARY ==========")
        print(f"Approved test cases: {len(approved_cases)}")
        print(f"Generated locators: {len(definitions)}")
        print(f"Failed locators: {len(failures)}")
        print(f"JSON output: {LOCATOR_JSON}")
        print(f"JavaScript output: {LOCATOR_JS}")


if __name__ == "__main__":
    generator = LocatorGenerator()
    generator.run()
