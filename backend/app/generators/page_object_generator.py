
import json
import re
from pathlib import Path
from datetime import datetime, timezone


PROJECT_ROOT = Path(__file__).resolve().parents[3]

FRAMEWORK_DIR = (
    PROJECT_ROOT
    / "generated"
    / "frameworks"
    / "playwright_project"
)

LOCATOR_FILE = FRAMEWORK_DIR / "locator_definitions.json"

REVIEWED_FILE = (
    PROJECT_ROOT
    / "generated"
    / "test_cases"
    / "reviewed_test_cases.json"
)

PAGES_DIR = FRAMEWORK_DIR / "pages"


class PageObjectGenerator:

    def __init__(self):
        PAGES_DIR.mkdir(parents=True, exist_ok=True)

    @staticmethod
    def load_json(file_path):
        if not file_path.exists():
            raise FileNotFoundError(
                f"Required file not found: {file_path}"
            )

        with open(file_path, "r", encoding="utf-8") as file:
            return json.load(file)

    @staticmethod
    def to_identifier(value):
        """Convert a name into a safe JavaScript identifier."""

        value = re.sub(r"[^a-zA-Z0-9]+", "_", value)
        value = value.strip("_").lower()

        if not value:
            return "element"

        if value[0].isdigit():
            value = "element_" + value

        return value

    @staticmethod
    def to_class_name(module):
        """Convert module name into a JavaScript class name."""

        words = re.findall(r"[a-zA-Z0-9]+", module)

        name = "".join(word.title() for word in words)

        return name or "Generated"

    @staticmethod
    def create_locator_code(definition):
        """Convert locator metadata into Playwright JavaScript."""

        strategy = definition["strategy"]
        value = json.dumps(
            definition["value"],
            ensure_ascii=False
        )

        options = definition.get("options", {})

        if strategy == "getByPlaceholder":
            exact = str(
                options.get("exact", False)
            ).lower()

            return (
                f"this.page.getByPlaceholder("
                f"{value}, {{ exact: {exact} }})"
            )

        if strategy == "getByLabel":
            exact = str(
                options.get("exact", False)
            ).lower()

            return (
                f"this.page.getByLabel("
                f"{value}, {{ exact: {exact} }})"
            )

        if strategy == "getByTestId":
            return f"this.page.getByTestId({value})"

        if strategy == "css":
            return f"this.page.locator({value})"

        if strategy == "getByRole":
            role = json.dumps(
                definition.get("role", "button")
            )

            role_options = json.dumps(
                options,
                ensure_ascii=False
            )

            return (
                f"this.page.getByRole("
                f"{role}, {role_options})"
            )

        raise ValueError(
            f"Unsupported locator strategy: {strategy}"
        )

    def generate_page_object(self, module, definitions):

        class_name = self.to_class_name(module) + "Page"

        lines = [
            "// AUTO-GENERATED PAGE OBJECT.",
            "// Generated by PageObjectGenerator.",
            "// Do not edit manually.",
            "",
            'import { expect } from "@playwright/test";',
            "",
            f"export class {class_name} {{",
            "",
            "    constructor(page) {",
            "        this.page = page;",
            "    }",
            ""
        ]

        used_names = set()

        for definition in definitions:

            element_name = self.to_identifier(
                definition["element_name"]
            )

            if element_name in used_names:
                element_name += "_" + self.to_identifier(
                    definition["test_case_id"]
                )

            used_names.add(element_name)

            locator_code = self.create_locator_code(
                definition
            )

            lines.extend([
                f"    // Locator for {definition['test_case_id']}",
                f"    get {element_name}() {{",
                f"        return {locator_code};",
                "    }",
                "",
                f"    async expect_{element_name}_visible() {{",
                f"        await expect(this.{element_name}).toBeVisible();",
                "    }",
                ""
            ])

        lines.extend([
            "}",
            ""
        ])

        return "\n".join(lines), class_name

    def run(self):

        print("\n======================================")
        print(" PAGE OBJECT MODEL GENERATOR")
        print("======================================")

        locator_data = self.load_json(LOCATOR_FILE)
        reviewed_data = self.load_json(REVIEWED_FILE)

        if isinstance(reviewed_data, dict):
            test_cases = reviewed_data.get("test_cases", [])
        else:
            test_cases = reviewed_data

        approved_cases = {
            case["test_case_id"]: case
            for case in test_cases
            if case.get("review_status") == "approved"
        }

        definitions = locator_data.get("definitions", [])

        # Never generate page objects for unapproved test cases.
        definitions = [
            definition for definition in definitions
            if definition.get("test_case_id") in approved_cases
        ]

        print(f"Approved test cases: {len(approved_cases)}")
        print(f"Available locator definitions: {len(definitions)}")

        if not definitions:
            print("No approved locator definitions found.")
            return

        # Group locators by application module.
        grouped_definitions = {}

        for definition in definitions:

            test_case = approved_cases[
                definition["test_case_id"]
            ]

            module = test_case.get("module", "Generated")

            grouped_definitions.setdefault(
                module, []
            ).append(definition)

        generated_files = []

        for module, module_definitions in grouped_definitions.items():

            javascript, class_name = self.generate_page_object(
                module,
                module_definitions
            )

            file_name = (
                self.to_identifier(module)
                + "_page.js"
            )

            output_file = PAGES_DIR / file_name

            output_file.write_text(
                javascript,
                encoding="utf-8"
            )

            generated_files.append({
                "module": module,
                "class_name": class_name,
                "file": file_name,
                "locator_count": len(module_definitions)
            })

            print(f"\nGenerated page class: {class_name}")
            print(f"Output file: {output_file}")

        summary = {
            "generated_at": datetime.now(
                timezone.utc
            ).isoformat(),
            "total_page_objects": len(generated_files),
            "generated_files": generated_files
        }

        summary_file = FRAMEWORK_DIR / "page_object_summary.json"

        summary_file.write_text(
            json.dumps(summary, indent=4),
            encoding="utf-8"
        )

        print("\n========== POM GENERATION SUMMARY ==========")
        print(f"Page objects generated: {len(generated_files)}")
        print(f"Summary: {summary_file}")


if __name__ == "__main__":
    generator = PageObjectGenerator()
    generator.run()
